fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let design = manifest.join("../ctdesign");
    let tengen = Tengen::load(
        &design,
        &[design.join("src/lib.rs"), manifest.join("src/design.rs")],
    );
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("tengen.rs"), tengen.constants(CONSTANTS)).expect("write tengen.rs");
}
