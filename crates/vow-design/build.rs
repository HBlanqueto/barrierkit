//! Generates `tengen.rs` constants from the Tengen JSON files.

use std::path::{Path, PathBuf};
use std::{env, fs};

use serde_json::Value;

#[path = "build/appearance.rs"]
mod appearance;
#[path = "build/color.rs"]
mod color;
#[path = "build/controls.rs"]
mod controls;
#[path = "build/json.rs"]
mod json;
#[path = "build/menu.rs"]
mod menu;
#[path = "build/settings.rs"]
mod settings;
#[path = "build/shell.rs"]
mod shell;
#[path = "build/sidebar.rs"]
mod sidebar;
#[path = "build/views.rs"]
mod views;
#[path = "build/window.rs"]
mod window;

use appearance::*;
use color::*;
use controls::*;
use json::*;
use menu::*;
use settings::*;
use shell::*;
use sidebar::*;
use views::*;
use window::*;

const TOKENS: &str = "tengen/tokens.json";
const COMPONENTS: &str = "tengen/components.json";

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let tokens_path = manifest.join(TOKENS);
    let components_path = manifest.join(COMPONENTS);
    println!("cargo:rerun-if-changed={}", tokens_path.display());
    println!("cargo:rerun-if-changed={}", components_path.display());

    let tokens = load(&tokens_path);
    let components = load(&components_path);
    let mut out = String::from(
        "// @generated by build.rs from tengen/tokens.json and tengen/components.json.\n\
         // Do not edit: change the JSON in crates/vow-design/tengen and rebuild.\n\n",
    );

    emit_titlebar(&mut out, &tokens, &components);
    emit_window(&mut out, &tokens, &components);
    emit_dialog(&mut out, &tokens, &components);
    emit_popup(&mut out, &tokens, &components);
    emit_tints(&mut out, &tokens, &components);
    emit_slider(&mut out, &components);
    emit_checkbox(&mut out, &tokens, &components);
    emit_switch(&mut out, &tokens, &components);
    emit_segmented(&mut out, &tokens, &components);
    emit_focus_ring(&mut out, &components);
    emit_button(&mut out, &tokens, &components);
    emit_text_field(&mut out, &tokens, &components);
    emit_progress(&mut out, &tokens, &components);
    emit_tooltip(&mut out, &tokens, &components);
    emit_titlebar_rail(&mut out, &components);
    emit_fullscreen_glass(&mut out, &components);
    emit_backdrop(&mut out, &components);
    emit_symbol(&mut out, &components);
    emit_slider_fat(&mut out, &components);
    emit_compact(&mut out, &tokens, &components);
    emit_list_group(&mut out, &tokens, &components);
    emit_space(&mut out, &tokens);
    emit_split_view(&mut out, &components);
    emit_views(&mut out, &tokens, &components);
    emit_wallpaper(&mut out, &tokens, &components);
    emit_traffic(&mut out, &tokens, &components);
    emit_font_families(&mut out, &tokens);
    emit_typography(&mut out, &tokens);
    emit_shadows(&mut out, &tokens);
    emit_palettes(&mut out, &tokens, &components);
    emit_shell(&mut out, &tokens, &components);
    emit_sidebar(&mut out, &tokens, &components);
    emit_menu(&mut out, &tokens, &components);
    emit_menu_popover(&mut out, &tokens, &components);
    emit_metrics(&mut out, &tokens, &components);
    emit_settings(&mut out, &tokens, &components);

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("tengen.rs"), out).expect("write tengen.rs");
}
