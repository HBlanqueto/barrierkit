#!/bin/sh
set -eu

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root/crates/ctdesign/tengen"

jq -nr --slurpfile tokens tokens.json --slurpfile components components.json '
($tokens[0] | del(.themes, ."default-theme")) as $base
| ($tokens[0].themes) as $themes
| ($components[0]) as $parts
| ([$base, $parts] | map([paths(type != "object" and type != "array")] | map(join("."))) | add) as $leaves
| ($themes.light | keys) as $colors
| def css_name: map(tostring) | if .[0] == "components" then .[1:] else . end | "--bk-" + join("-");
  def css_value:
    if type == "string" then
      . as $text
      | if test("^\\{[a-z0-9-]+\\}$") then "var(--bk-\(.[1:-1]))"
      elif ($leaves | index([$text])) then "var(\(split(".") | css_name))"
      elif ($colors | index([$text])) then "var(--bk-\(.))"
      else . end
    elif type == "array" then
      if all(.[]; type != "array" and type != "object") then map(css_value) | join(" ") else empty end
    else tostring end;
  def declarations:
    [paths(type != "object") as $path
     | select(all($path[]; type == "string"))
     | getpath($path) | css_value as $value
     | "  \($path | css_name): \($value);"]
    | join("\n");
  def theme($name): $themes[$name] | declarations;
"/* Generated by scripts/tengen-css.sh from crates/ctdesign/tengen; do not edit. */",
":root {",
($base | declarations),
($parts | declarations),
"}",
"",
":root, [data-theme=\"light\"] {", theme("light"), "}",
"",
"@media (prefers-color-scheme: dark) {",
"  :root:not([data-theme=\"light\"]) {",
(theme("dark") | gsub("(?m)^"; "  ")),
"  }",
"}",
"",
"[data-theme=\"dark\"] {", theme("dark"), "}",
"",
"[data-theme=\"dark-tint\"] {", theme("dark-tint"), "}"
'
